function path(ctx:CanvasRenderingContext2D,points:string,color:string,outline=false){
 ctx.beginPath();
 points.split(' ').forEach((pair,index)=>{
  const [x,y]=pair.split(',').map(Number);
  if(index===0)ctx.moveTo(x,y);else ctx.lineTo(x,y);
 });
 ctx.closePath();
 if(outline){ctx.lineJoin='round';ctx.lineWidth=2;ctx.strokeStyle='#140f22';ctx.stroke();}
 ctx.fillStyle=color;ctx.fill();
}
